<?php

namespace App\Pdf;

/**
 * Charter tokens of the PDF themes (PDF_GOTENBERG.md § 8.1): the colour and font custom properties of the light theme
 * of app4 (admin) and of the kpi-layer used by app3 (public), copied as they are so that the PDFs follow the charters
 * without any hand-copied colour.
 */
final class ChartTokens
{
    /** Charter source of each theme, relative to the legacy tree (sources/). */
    public const SOURCES = [
        PdfTheme::Admin->value => 'app4/assets/css/admin.css',
        PdfTheme::Public->value => 'kpi-layer/app/assets/css/kpi-theme.css',
    ];

    /** Only the light theme is printed: blocks opened by `:root` or `@theme`, never `.dark` (§ 8.5). */
    private const LIGHT_BLOCK = '/^(?::root|@theme(?:\s+static)?)\s*\{(.*?)^\}/ms';

    private const TOKEN = '/^\s*(--(?:ui-)?(?:color|font)-[a-z0-9-]+)\s*:\s*([^;]+);/m';

    /**
     * Custom properties declared by the light-theme blocks of a charter stylesheet, in declaration order (a later
     * declaration of the same name wins, as in the browser).
     *
     * @return array<string, string>
     */
    public static function extract(string $css): array
    {
        $css = preg_replace('#/\*.*?\*/#s', '', $css) ?? $css;
        preg_match_all(self::LIGHT_BLOCK, $css, $blocks);

        $tokens = [];
        foreach ($blocks[1] as $block) {
            preg_match_all(self::TOKEN, $block, $declarations, PREG_SET_ORDER);
            foreach ($declarations as [, $name, $value]) {
                $tokens[$name] = trim($value);
            }
        }

        return $tokens;
    }

    /** Stylesheet committed under assets/pdf/tokens/, regenerated by `app:pdf:sync-assets`. */
    public static function stylesheet(PdfTheme $theme, string $css): string
    {
        $lines = [];
        foreach (self::extract($css) as $name => $value) {
            $lines[] = sprintf('  %s: %s;', $name, $value);
        }

        return sprintf(
            "/* Generated by `bin/console app:pdf:sync-assets` from sources/%s: do not edit by hand. */\n:root {\n%s\n}\n",
            self::SOURCES[$theme->value],
            implode("\n", $lines),
        );
    }
}
